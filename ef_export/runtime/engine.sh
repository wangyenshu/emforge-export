# --------------------------------------------------------------------------
# Python for BUILD_PREFIX (a venv: same layout as a conda env for our needs)
# --------------------------------------------------------------------------
ef_select_python() {  # spec  -> prints interpreter path
  local spec="$1" pref="$2" c v best="" cand=()
  for c in "python$pref" python3.15 python3.14 python3.13 python3.12 python3.11 python3.10 python3; do
    [ -z "$c" ] && continue
    v="$(PATH="$EF_SYS_PATH" "$c" -c 'import sys;print("%d.%d.%d"%sys.version_info[:3])' 2>/dev/null)" || continue
    if ef_spec_ok "$v" "$spec" && PATH="$EF_SYS_PATH" "$c" -c 'import venv' 2>/dev/null; then
      echo "$(ef_which_system "$c")"; return 0
    fi
  done
  # bootstrap from python.org sources
  local s
  for s in "python-$pref" ${EF_PYTHON_SRCS[@]+"${EF_PYTHON_SRCS[@]}"}; do
    declare -F "ef_srcdef_$(printf '%s' "$s" | tr -c 'A-Za-z0-9\n' '_')" >/dev/null || continue
    v="${s#python-}"
    case "$s" in python-"$pref"|python-"$pref".*) ;; *) ef_spec_ok "$v" "$spec" || continue ;; esac
    ef_spec_ok "$v" "$spec" || continue
    [ "${EF_DRY:-0}" = 1 ] && { echo "(bootstrap $s)"; return 0; }
    ef_bootstrap_src "$s" >&2 || return 1
    echo "$EF_TOOLS/$s/bin/python${v%.*}"; return 0
  done
  for s in ${EF_PYTHON_SRCS[@]+"${EF_PYTHON_SRCS[@]}"}; do
    v="${s#python-}"
    case "$v" in $pref.*) ;; *) continue ;; esac
    [ "${EF_DRY:-0}" = 1 ] && { echo "(bootstrap $s)"; return 0; }
    ef_bootstrap_src "$s" >&2 || return 1
    echo "$EF_TOOLS/$s/bin/python${v%.*}"; return 0
  done
  return 1
}

ef_make_build_prefix() {  # dir python-spec preferred-major.minor
  local dir="$1" spec="$2" pref="$3" py ver key tmpl
  py="$(ef_select_python "$spec" "$pref")" || ef_die "no Python matching '${spec:-any}' for BUILD_PREFIX"
  ver="$("$py" -c 'import sys;print("%d.%d.%d"%sys.version_info[:3])')"
  key="$(ef_hash_str "$py:$ver:$dir")"
  tmpl="$EF_ROOT/tmp/venv-templates/$key"
  rm -rf "$dir"
  if [ -f "$tmpl/.ef-done" ]; then
    cp -a "$tmpl/env" "$dir"
  else
    if ! "$py" -m venv "$dir" >/dev/null 2>&1; then
      rm -rf "$dir"
      "$py" -m venv --without-pip "$dir" || ef_die "cannot create a venv with $py"
      local whl
      whl="$(ef_helper obtain "$EF_SRC_CACHE" "$EF_PIP_WHEEL_SHA256" "$EF_OFFLINE" "$EF_EXTRA_CACHES" "$EF_PIP_WHEEL_URL")"
      "$dir/bin/python" "$whl/pip" install -q --no-index "$whl" || ef_die "cannot bootstrap pip"
    fi
    rm -rf "$tmpl"; mkdir -p "$tmpl"; cp -a "$dir" "$tmpl/env"; touch "$tmpl/.ef-done"
  fi
  [ -e "$dir/bin/python3" ] || ln -s python "$dir/bin/python3"
  EF_BUILD_PY_VER="${ver%.*}"
  ef_log "BUILD_PREFIX python: $py ($ver)"
}

