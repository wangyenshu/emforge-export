# ==========================================================================
# emforge-export runtime engine
#
# Emulates what rattler-build does for one output, without any package
# channel: a fresh host prefix ($PREFIX) and build prefix ($BUILD_PREFIX)
# are assembled from previously built packages and native tools, sources
# are fetched + verified + patched, the recipe script runs with the same
# environment (variables, activation scripts) rattler-build would set up,
# and the new files of $PREFIX become a package in $EF_ROOT/pkgs.
# Written for bash >= 3.2 (macOS) and GNU or BSD userlands.
# ==========================================================================

EF_SELF="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")"
EF_SYS_PATH="$PATH"
EF_START_DIR="$(pwd)"

ef_c_bold=""; ef_c_red=""; ef_c_yel=""; ef_c_grn=""; ef_c_dim=""; ef_c_off=""
if [ -t 2 ] && [ -z "${NO_COLOR:-}" ]; then
  ef_c_bold=$'\033[1m'; ef_c_red=$'\033[31m'; ef_c_yel=$'\033[33m'
  ef_c_grn=$'\033[32m'; ef_c_dim=$'\033[2m'; ef_c_off=$'\033[0m'
fi
ef_log()  { printf '%s[ef]%s %s\n' "$ef_c_dim" "$ef_c_off" "$*" >&2; }
ef_info() { printf '%s[ef]%s %s%s%s\n' "$ef_c_dim" "$ef_c_off" "$ef_c_bold" "$*" "$ef_c_off" >&2; }
ef_ok()   { printf '%s[ef]%s %s%s%s\n' "$ef_c_dim" "$ef_c_off" "$ef_c_grn" "$*" "$ef_c_off" >&2; }
ef_warn() { printf '%s[ef] warning:%s %s\n' "$ef_c_yel" "$ef_c_off" "$*" >&2
            EF_WARNINGS+=("$*"); }
ef_die()  { printf '%s[ef] error:%s %s\n' "$ef_c_red" "$ef_c_off" "$*" >&2; exit 1; }
ef_q()    { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }
EF_WARNINGS=()

ef_cpu_count() {
  if [ -n "${CPU_COUNT:-}" ]; then echo "$CPU_COUNT"; return; fi
  getconf _NPROCESSORS_ONLN 2>/dev/null || sysctl -n hw.ncpu 2>/dev/null || echo 2
}

ef_detect_platform() {
  local s m
  s="$(uname -s)"; m="$(uname -m)"
  case "$s" in
    Darwin) case "$m" in arm64|aarch64) echo osx-arm64 ;; *) echo osx-64 ;; esac ;;
    Linux)  case "$m" in aarch64|arm64) echo linux-aarch64 ;; ppc64le) echo linux-ppc64le ;; *) echo linux-64 ;; esac ;;
    *) echo linux-64 ;;
  esac
}

ef_usage() {
  cat <<EOF
Usage: $(basename "$EF_SELF") [options] [PACKAGE...]

Standalone build of emscripten-forge recipe(s): ${EF_TARGETS[*]}
Generated by emforge-export from emscripten-forge/recipes ${EF_RECIPES_REV}.
No conda, mamba, pixi or rattler-build is used, and no conda channel
(prefix.dev, anaconda.org) is contacted.

Options:
  -C, --root DIR          work root (default: \$EF_ROOT or ./ef-build)
  -p, --prefix DIR        final install prefix (default: <root>/prefix)
  -j, --jobs N            parallel jobs passed as CPU_COUNT (default: all cores)
  -l, --list              show the build plan and exit
      --only NAME         build only this package (its deps must be built)
      --rebuild NAME      rebuild NAME even if it is up to date (repeatable)
      --force             rebuild everything
      --tests             also run the script tests of the requested packages
                          (builds what the tests need; re-running with --tests
                          only runs the tests of packages already built)
      --tests-all         run the script tests of every package of the plan
      --skip-tests        skip package_contents tests too
      --strict-tests      a failing package_contents test stops the build
                          (default: reported as a warning)
      --no-assemble       do not assemble the final prefix
      --conda-pkgs        also write conda .tar.bz2 packages + repodata.json
                          to <root>/channel (installable with conda/mamba)
      --check             only check/provision native tools, then exit
      --tools MODE        auto (default): system tools when suitable, else
                          pip/source/binary bootstrap; system: never
                          bootstrap; bootstrap: prefer pinned bootstraps
      --install-system-deps
                          try to install missing tools with apt/dnf/brew/pacman
      --offline           never download; use caches only
      --cache DIR         download cache shared between roots
                          (default: \$EF_CACHE or ~/.cache/emforge-export)
      --source-cache DIR  extra directory with pre-downloaded sources
                          (matched by file name or sha256, repeatable)
      --isolation MODE    strict (default, like rattler-build) or none
      --keep-work         keep the work/host/build dirs of the last package
      --link-staging      hard-link a staging cache's work directory into the
                          outputs that inherit it instead of copying it (fast
                          for big source trees; an output whose script edits
                          a cached file in place makes the cache rebuild)
      --extract DIR       write the embedded recipe files to DIR and exit
  -h, --help              this help

Environment: EF_ROOT, EF_PREFIX, CPU_COUNT, EF_MIRRORS (space separated
URL templates with {sha256} / {filename}), EF_PKG_CONFIG_SYSTEM=1 (let
pkg-config also search /usr), EF_NO_GIT_FALLBACK=1.
EOF
}

