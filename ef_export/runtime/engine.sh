ef_pkg_dir() { echo "$EF_PKGS/$1"; }

ef_install_pkg() {  # ident prefix mode
  local d
  d="$(ef_pkg_dir "$1")"
  [ -f "$d/.ef-done" ] || ef_die "package $1 is not built yet (run without --only)"
  ef_helper install "$d" "$2" "$3"
  # keep emscripten's cache (compiled system libraries, ports) across
  # builds.  emscripten clears its cache when the path of its LLVM changes,
  # so there is one cache per emscripten package and BUILD_PREFIX path
  # (builds always use bld/build_env, tests bld/test_build_env).
  if [ -d "$2/opt/emsdk/upstream/emscripten" ] && [ "$3" = link ]; then
    local c="$2/opt/emsdk/upstream/emscripten/cache" pc
    pc="$EF_ROOT/emcache/$1@$(basename "$2")"
    if [ ! -L "$c" ]; then
      if [ ! -d "$pc" ]; then mkdir -p "$pc"; [ -d "$c" ] && cp -a "$c/." "$pc/" 2>/dev/null || true; fi
      rm -rf "$c"; ln -s "$pc" "$c"
    fi
  fi
}

