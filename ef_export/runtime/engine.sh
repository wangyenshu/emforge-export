ef_find_python() {
  local c v
  for c in python3 python3.14 python3.13 python3.12 python3.11 python3.10 python3.9 python3.8 python; do
    if command -v "$c" >/dev/null 2>&1; then
      v="$("$c" -c 'import sys;print("%d%03d"%sys.version_info[:2])' 2>/dev/null || echo 0)"
      if [ "$v" -ge 3008 ]; then command -v "$c"; return 0; fi
    fi
  done
  return 1
}

ef_helper() { "$EF_PY" -I "$EF_HELPER" "$@"; }

ef_setup_root() {
  EF_ROOT="$(mkdir -p "$EF_ROOT" && cd "$EF_ROOT" && pwd)"
  EF_PREFIX="${EF_PREFIX:-$EF_ROOT/prefix}"
  # downloads (checksummed sources, pip wheels, git mirrors, emscripten's
  # compiled system libraries) are shared by every root
  EF_CACHE="${EF_CACHE:-${XDG_CACHE_HOME:-$HOME/.cache}/emforge-export}"
  mkdir -p "$EF_CACHE" && EF_CACHE="$(cd "$EF_CACHE" && pwd)"
  EF_SRC_CACHE="$EF_CACHE/sources"
  EF_TOOLS="$EF_ROOT/tools"; EF_PKGS="$EF_ROOT/pkgs"; EF_LOGS="$EF_ROOT/logs"
  EF_BLD="$EF_ROOT/bld"
  mkdir -p "$EF_CACHE" "$EF_SRC_CACHE" "$EF_TOOLS" "$EF_PKGS" "$EF_LOGS" "$EF_BLD" "$EF_ROOT/tmp"
  # build directories left behind by an interrupted run
  local t; for t in "$EF_ROOT"/tmp/trash-*; do
    [ -e "$t" ] && { ( chmod -R u+w "$t" 2>/dev/null; rm -rf "$t" ) >/dev/null 2>&1 & }
  done
  EF_HELPER="$EF_ROOT/ef-helper-$EF_SCRIPT_ID.py"
  if [ ! -f "$EF_HELPER" ]; then
    ef_write_helper > "$EF_HELPER.tmp" && mv "$EF_HELPER.tmp" "$EF_HELPER"
  fi
  EF_RECIPES="$EF_ROOT/recipes/$EF_SCRIPT_ID"
  if [ ! -f "$EF_RECIPES/.ef-complete" ]; then
    ef_extract_payload "$EF_RECIPES"
  fi
}

ef_extract_payload() {
  local dest="$1"
  rm -rf "$dest.tmp"; mkdir -p "$dest.tmp"
  "$EF_PY" -I - "$EF_SELF" "$dest.tmp" <<'PYEOF' || ef_die "cannot unpack the recipe files embedded in $EF_SELF"
import base64, os, sys
self_path, dest = sys.argv[1], os.path.realpath(sys.argv[2])
data = open(self_path, "rb").read()
marker = b"\n__EF_PAYLOAD_BEGIN__\n"
i = data.rfind(marker)
if i < 0:
    sys.exit("payload marker not found in " + self_path)
pos, n = i + len(marker), 0
while True:
    j = data.find(b"#@ef-file ", pos)
    if j < 0:
        break
    eol = data.index(b"\n", j)
    tag, enc, mode, rel = data[j + 10:eol].decode().split(" ", 3)
    end = data.index(b"#@ef-end " + tag.encode(), eol + 1)
    body = data[eol + 1:end]
    out = os.path.realpath(os.path.join(dest, rel))
    if not out.startswith(dest + os.sep):
        sys.exit("bad path in payload: " + rel)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    if enc in ("text-nonl", "symlink"):
        body = body[:-1]
    if enc == "symlink":
        os.symlink(body.decode(), out)
    else:
        if enc == "base64":
            body = base64.b64decode(b"".join(body.split()))
        with open(out, "wb") as f:
            f.write(body)
        os.chmod(out, int(mode, 8))
    pos, n = end, n + 1
if n == 0:
    sys.exit("no files in the payload of " + self_path)
PYEOF
  touch "$dest.tmp/.ef-complete"
  rm -rf "$dest"; mv "$dest.tmp" "$dest"
}

