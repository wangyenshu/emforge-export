EF_MISSING=()
EF_MISSING_PKGS=()

ef_pkg_manager() {
  if command -v apt-get >/dev/null 2>&1; then echo apt
  elif command -v dnf >/dev/null 2>&1; then echo dnf
  elif command -v brew >/dev/null 2>&1; then echo brew
  elif command -v pacman >/dev/null 2>&1; then echo pacman
  else echo none; fi
}

ef_record_missing() {  # tool spec
  local pm hint=""
  pm="$(ef_pkg_manager)"
  case "$pm" in
    apt) hint="$T_APT" ;; dnf) hint="$T_DNF" ;; brew) hint="$T_BREW" ;; pacman) hint="$T_PACMAN" ;;
  esac
  EF_MISSING+=("$1${2:+ ($2)}${hint:+  -> $pm: $hint}")
  [ -n "$hint" ] && EF_MISSING_PKGS+=($hint)
  return 0
}

ef_tool_reset() {
  T_EXE=(); T_VER="--version"; T_SRC=(); T_PIP=""; T_DATA=(); T_SPECIAL=""; T_SHIM=""; T_NEED=()
  T_PC=(); T_HEADER=""
  T_APT=""; T_DNF=""; T_BREW=""; T_PACMAN=""; T_OPTIONAL=0
}

ef_tool() {  # name spec   (EF_DRY=1: only check availability)
  local name="$1" spec="$2" fn
  # a leading '~' marks a version that comes from a variant pin, not from
  # the recipe: honoured when cheap (pip), otherwise not enforced
  EF_TSOFT=0
  case "$spec" in "~"*) EF_TSOFT=1; spec="${spec#\~}" ;; esac
  fn="ef_tooldef_$(printf '%s' "$name" | tr -c 'A-Za-z0-9\n' '_')"
  ef_tool_reset
  if ! declare -F "$fn" >/dev/null; then
    ef_tool_unknown "$name" "$spec"; return $?
  fi
  "$fn"
  if [ -n "$T_SPECIAL" ]; then
    "ef_special_$T_SPECIAL" "$name" "$spec"; return $?
  fi
  ef_tool_generic "$name" "$spec"
}

ef_tool_unknown() {
  local p
  p="$(ef_which_system "$1")" && { [ "${EF_DRY:-0}" = 1 ] || ef_log "tool $1: $p (not in registry)"; return 0; }
  if [ "${EF_DRY:-0}" = 1 ]; then
    EF_UNKNOWN_TOOLS+=("$1"); return 0
  fi
  ef_warn "build requirement '$1${2:+ $2}' has no provider in this script; continuing without it"
  return 0
}
EF_UNKNOWN_TOOLS=()

ef_tool_generic() {
  local name="$1" spec="$2" exe p ver mismatch="" mismatch_ver="" src
  if [ "$EF_TOOLS_MODE" != bootstrap ] || { [ -z "$T_PIP" ] && [ ${#T_SRC[@]} -eq 0 ]; }; then
    for exe in ${T_EXE[@]+"${T_EXE[@]}"}; do
      p="$(ef_which_system "$exe")" || continue
      if ! ef_tool_has_files "$p" ${T_NEED[@]+"${T_NEED[@]}"}; then
        mismatch="$p"; mismatch_ver="incomplete: no ${EF_TOOL_LACKS}"; continue
      fi
      ver=""
      if [ -n "$spec" ] && [ -n "$T_VER" ]; then
        ver="$(ef_tool_version "$p" "$T_VER" || true)"
        if ! ef_spec_ok "$ver" "$spec"; then
          if [ "$EF_TSOFT" = 1 ] && [ -z "$T_PIP" ]; then
            [ "${EF_DRY:-0}" = 1 ] && return 0
            ef_mirror_data "$p" ${T_DATA[@]+"${T_DATA[@]}"}
            ef_log "tool $name: system $p${ver:+ ($ver)} (variant pin $spec not enforced)"
            return 0
          fi
          mismatch="$p"; mismatch_ver="$ver"; continue
        fi
      fi
      [ "${EF_DRY:-0}" = 1 ] && return 0
      ef_mirror_data "$p" ${T_DATA[@]+"${T_DATA[@]}"}
      ef_log "tool $name${spec:+ $spec}: system $p${ver:+ ($ver)}"
      return 0
    done
  fi
  if [ "$EF_TOOLS_MODE" != system ] || [ -n "$mismatch" ] || [ ${#T_EXE[@]} -eq 0 ]; then
    if [ -n "$T_PIP" ]; then
      [ "${EF_DRY:-0}" = 1 ] && return 0
      ef_pip_build "$T_PIP" "$spec"; return $?
    fi
    if [ ${#T_SRC[@]} -gt 0 ]; then
      src="$(ef_pick_src "$spec" "${T_SRC[@]}")"
      if [ -n "$src" ]; then
        [ "${EF_DRY:-0}" = 1 ] && return 0
        ef_bootstrap_src "$src" || return 1
        ef_link_prefix "$EF_TOOLS/$src"
        ef_log "tool $name${spec:+ $spec}: bootstrapped $src"
        return 0
      fi
    fi
  fi
  if [ -n "$T_SHIM" ]; then
    [ "${EF_DRY:-0}" = 1 ] && return 0
    "ef_shim_$T_SHIM"; ef_log "tool $name: shim"; return 0
  fi
  if [ -n "$mismatch" ]; then
    [ "${EF_DRY:-0}" = 1 ] && return 0
    ef_warn "tool $name: recipe wants '$spec', using system $mismatch ($mismatch_ver)"
    ef_mirror_data "$mismatch" ${T_DATA[@]+"${T_DATA[@]}"}
    return 0
  fi
  if [ "$T_OPTIONAL" = 1 ]; then
    [ "${EF_DRY:-0}" = 1 ] || ef_log "note: optional tool $name not found; continuing without it"
    return 0
  fi
  ef_record_missing "$name" "$spec"
  return 1
}

ef_tool_has_files() {  # exe-path rel-files...   (sets EF_TOOL_LACKS)
  local pfx f
  [ $# -le 1 ] && return 0
  pfx="$(dirname "$(dirname "$(ef_realpath "$1")")")"; shift
  for f in "$@"; do
    [ -e "$pfx/$f" ] || { EF_TOOL_LACKS="$f"; return 1; }
  done
  return 0
}

ef_pick_src() {  # spec src-ids...  -> first src whose version matches
  local spec="$1"; shift
  local s v
  for s in "$@"; do
    v="${s##*-}"
    if ef_spec_ok "$v" "$spec"; then echo "$s"; return 0; fi
  done
  return 0
}

ef_pip_build() {  # dist spec  -> install into BUILD_PREFIX venv
  local req
  req="$(ef_helper pip-spec "$1" "$2")"
  EF_PIP_QUEUE+=("$req")
}
EF_PIP_QUEUE=()

ef_pip_flush() {
  [ ${#EF_PIP_QUEUE[@]} -eq 0 ] && return 0
  ef_log "pip install (BUILD_PREFIX): ${EF_PIP_QUEUE[*]}"
  local try
  for try in 1 2 3; do
    if env -u PIP_NO_INDEX -u PIP_NO_DEPENDENCIES -u PIP_IGNORE_INSTALLED -u PIP_REQUIRE_VIRTUALENV \
         PIP_CACHE_DIR="$EF_CACHE/pip" PIP_DISABLE_PIP_VERSION_CHECK=1 \
         "$EF_B/bin/python" -m pip install --no-input -q --timeout 60 --retries 5 "${EF_PIP_QUEUE[@]}"; then
      EF_PIP_QUEUE=(); return 0
    fi
    [ "$EF_OFFLINE" = 1 ] && break
    ef_log "pip install failed (attempt $try), retrying"
  done
  ef_die "pip install failed: ${EF_PIP_QUEUE[*]}"
}

# build a pinned upstream release into $EF_TOOLS/<id>
ef_bootstrap_src() {
  local id="$1" fn dir work tarball rc
  dir="$EF_TOOLS/$id"
  [ -f "$dir/.ef-done" ] && return 0
  fn="ef_srcdef_$(printf '%s' "$id" | tr -c 'A-Za-z0-9\n' '_')"
  S_URL=(); S_SHA256=""; S_NEEDS=(); S_CONFIGURE=""; S_ENV=""; S_BUILD="autotools"
  declare -F "$fn" >/dev/null || ef_die "no bootstrap recipe for $id"
  "$fn"
  if [ "$S_BUILD" = none ]; then
    tarball="$(ef_helper obtain "$EF_SRC_CACHE" "$S_SHA256" "$EF_OFFLINE" "$EF_EXTRA_CACHES" "${S_URL[@]}")" || return 1
    rm -rf "$dir"; mkdir -p "$dir/src"
    tar -xf "$tarball" -C "$dir/src" || return 1
    touch "$dir/.ef-done"; return 0
  fi
  local need p extra_path=""
  for need in ${S_NEEDS[@]+"${S_NEEDS[@]}"}; do
    ef_tool_reset; "ef_tooldef_$(printf '%s' "$need" | tr -c 'A-Za-z0-9\n' '_')"
    p=""
    local e; for e in ${T_EXE[@]+"${T_EXE[@]}"}; do p="$(ef_which_system "$e")" && break; done
    if [ -z "$p" ]; then
      ef_bootstrap_src "${T_SRC[0]}" || return 1
      extra_path="$EF_TOOLS/${T_SRC[0]}/bin:$extra_path"
    fi
  done
  ef_info "bootstrapping $id from source"
  tarball="$(ef_helper obtain "$EF_SRC_CACHE" "$S_SHA256" "$EF_OFFLINE" "$EF_EXTRA_CACHES" "${S_URL[@]}")" || return 1
  work="$EF_ROOT/tmp/bootstrap-$id"
  rm -rf "$work" "$dir"; mkdir -p "$work"
  tar -xf "$tarball" -C "$work" || return 1
  work="$(find "$work" -mindepth 1 -maxdepth 1 -type d | head -n 1)"
  (
    set -e
    cd "$work"
    export PATH="$extra_path$EF_SYS_PATH"
    [ -n "$S_ENV" ] && eval "export $S_ENV"
    case "$S_BUILD" in
      autotools)
        # shellcheck disable=SC2086
        ./configure --prefix="$dir" $S_CONFIGURE
        make -j"$EF_JOBS"
        make install
        ;;
      infozip)
        make -f unix/Makefile generic CC="${CC:-cc}" \
          LOCAL_ZIP="-O2 -Wno-implicit-function-declaration -Wno-incompatible-pointer-types -DNO_LCHMOD" \
          LOCAL_UNZIP="-O2 -Wno-implicit-function-declaration -Wno-incompatible-pointer-types -DNO_LCHMOD" \
          || make -f unix/Makefile generic CC="${CC:-cc}"
        make -f unix/Makefile install prefix="$dir" MANDIR="$dir/share/man/man1"
        ;;
      *) echo "unknown bootstrap build style $S_BUILD"; exit 1 ;;
    esac
  ) > "$EF_LOGS/bootstrap-$id.log" 2>&1
  rc=$?
  if [ $rc -ne 0 ]; then
    tail -n 30 "$EF_LOGS/bootstrap-$id.log" >&2
    ef_die "bootstrap of $id failed (log: $EF_LOGS/bootstrap-$id.log)"
  fi
  rm -rf "$EF_ROOT/tmp/bootstrap-$id"
  touch "$dir/.ef-done"
}

# ---- special providers -----------------------------------------------------
ef_special_python() { return 0; }   # handled when BUILD_PREFIX is created

ef_special_native_lib() {  # a library for the build machine, from the system
  local m d found=""
  for m in ${T_PC[@]+"${T_PC[@]}"}; do
    if PATH="$EF_SYS_PATH" pkg-config --exists "$m" 2>/dev/null; then found="pkg-config $m"; break; fi
  done
  if [ -z "$found" ] && [ -n "$T_HEADER" ]; then
    for d in /usr/include /usr/local/include /usr/include/*-linux-gnu /opt/homebrew/include; do
      [ -f "$d/$T_HEADER" ] && { found="$d/$T_HEADER"; break; }
    done
  fi
  if [ -z "$found" ] && [ ${#T_PC[@]} -eq 0 ] && [ -z "$T_HEADER" ]; then found="(not checked)"; fi
  if [ -z "$found" ]; then
    if [ "$T_OPTIONAL" = 1 ]; then
      [ "${EF_DRY:-0}" = 1 ] || ef_warn "optional native library $1 not found"
      return 0
    fi
    ef_record_missing "$1" "$2"; return 1
  fi
  [ "${EF_DRY:-0}" = 1 ] || ef_log "tool $1: native library from the system ($found)"
  return 0
}

ef_special_cc() {  # gcc / gxx : a native compiler for the build machine
  local name="$1" exe p cc="" cxx=""
  for exe in ${T_EXE[@]+"${T_EXE[@]}"} cc clang; do
    p="$(ef_which_system "$exe")" && { [ "$name" = gxx ] && cxx="$p" || cc="$p"; break; }
  done
  if [ -z "$cc$cxx" ]; then ef_record_missing "$name" "$2"; return 1; fi
  [ "${EF_DRY:-0}" = 1 ] && return 0
  local CCV CXXV
  CCV="$(ef_which_system gcc || ef_which_system cc || ef_which_system clang || true)"
  CXXV="$(ef_which_system g++ || ef_which_system c++ || ef_which_system clang++ || true)"
  if [ "$U_TARGET" = native ]; then
    ef_activation_script "activate-gcc_${EF_BUILD_PLATFORM}.sh" "export CC=$(ef_q "$CCV")
export CXX=$(ef_q "$CXXV")
export CPP=\"\$CC -E\"
export AR=\"\$(command -v ar || command -v llvm-ar || echo ar)\"
export NM=\"\$(command -v nm || echo nm)\"
export RANLIB=\"\$(command -v ranlib || echo ranlib)\"
export STRIP=\"\$(command -v strip || echo strip)\"
export HOST=\"\$(\$CC -dumpmachine 2>/dev/null || echo unknown)\"
export BUILD=\"\$HOST\"
export CONDA_TOOLCHAIN_HOST=\"\$HOST\"
export CONDA_TOOLCHAIN_BUILD=\"\$HOST\"
export CFLAGS=\"-O2 -fPIC -pipe -isystem \$PREFIX/include \${CFLAGS:-}\"
export CXXFLAGS=\"-O2 -fPIC -pipe -isystem \$PREFIX/include \${CXXFLAGS:-}\"
export CPPFLAGS=\"-DNDEBUG -isystem \$PREFIX/include \${CPPFLAGS:-}\"
export LDFLAGS=\"-L\$PREFIX/lib -Wl,-rpath,\$PREFIX/lib \${LDFLAGS:-}\"
export CMAKE_ARGS=\"-DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX=\$PREFIX -DCMAKE_PREFIX_PATH=\$PREFIX -DCMAKE_INSTALL_LIBDIR=lib \${CMAKE_ARGS:-}\"
export CC_FOR_BUILD=\"\$CC\"
export CXX_FOR_BUILD=\"\$CXX\""
  else
