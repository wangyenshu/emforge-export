ef_special_openjdk() {
  local name="$1" spec="$2" major="" cands=() h v jdk=""
  major="$(printf '%s' "$spec" | sed -n 's/^[=>~ ]*\([0-9][0-9]*\).*/\1/p')"
  [ -z "$major" ] && major=21
  if [ "$EF_TOOLS_MODE" != bootstrap ]; then
    [ -n "${JAVA_HOME:-}" ] && cands+=("$JAVA_HOME")
    if h="$(ef_which_system javac)"; then cands+=("$(dirname "$(dirname "$(ef_realpath "$h")")")"); fi
    for h in /usr/lib/jvm/* /Library/Java/JavaVirtualMachines/*/Contents/Home /opt/homebrew/opt/openjdk*/libexec/openjdk.jdk/Contents/Home; do
      [ -x "$h/bin/javac" ] && cands+=("$h")
    done
    for h in ${cands[@]+"${cands[@]}"}; do
      [ -x "$h/bin/javac" ] && [ -x "$h/bin/jlink" ] || continue
      v="$(ef_jdk_version "$h")"
      if ef_spec_ok "$v" "${spec:-$major}"; then jdk="$h"; break; fi
    done
  fi
  [ "${EF_DRY:-0}" = 1 ] && return 0
  if [ -z "$jdk" ]; then
    local os arch dir t meta link sha
    case "$(uname -s)" in Darwin) os=mac ;; *) os=linux ;; esac
    case "$(uname -m)" in x86_64|amd64) arch=x64 ;; aarch64|arm64) arch=aarch64 ;; *) arch="$(uname -m)" ;; esac
    dir="$EF_TOOLS/temurin-$major-$os-$arch"
    if [ ! -f "$dir/.ef-done" ]; then
      [ "$EF_OFFLINE" = 1 ] && ef_die "offline and no JDK $major available"
      ef_info "downloading Eclipse Temurin JDK $major (api.adoptium.net)"
      meta="$(curl -fsSL "https://api.adoptium.net/v3/assets/latest/$major/hotspot?architecture=$arch&image_type=jdk&os=$os&vendor=eclipse")" \
        || ef_die "cannot query api.adoptium.net"
      link="$(printf '%s' "$meta" | "$EF_PY" -c 'import json,sys;print(json.load(sys.stdin)[0]["binary"]["package"]["link"])')"
      sha="$(printf '%s' "$meta" | "$EF_PY" -c 'import json,sys;print(json.load(sys.stdin)[0]["binary"]["package"]["checksum"])')"
      t="$(ef_helper obtain "$EF_SRC_CACHE" "$sha" "$EF_OFFLINE" "$EF_EXTRA_CACHES" "$link")" || return 1
      rm -rf "$dir"; mkdir -p "$dir"; tar -xf "$t" -C "$dir"
      touch "$dir/.ef-done"
    fi
    jdk="$(find "$dir" -mindepth 1 -maxdepth 4 -type f -path '*/bin/javac' | head -n 1)"
    jdk="$(dirname "$(dirname "$jdk")")"
  fi
  mkdir -p "$EF_B/lib" "$EF_B/bin"
  rm -f "$EF_B/lib/jvm"; ln -s "$jdk" "$EF_B/lib/jvm"
  local x; for x in "$jdk"/bin/*; do [ -e "$EF_B/bin/$(basename "$x")" ] || ln -s "$x" "$EF_B/bin/"; done
  ef_activation_script "openjdk_activate.sh" 'export JAVA_HOME="$CONDA_PREFIX/lib/jvm"
export JAVA_LD_LIBRARY_PATH="$JAVA_HOME/lib/server"'
  ef_log "tool openjdk${spec:+ $spec}: $jdk ($(ef_jdk_version "$jdk"))"
}

