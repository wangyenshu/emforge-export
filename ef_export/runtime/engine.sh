ef_kv() { printf 'export %s=%s\n' "$1" "$(ef_q "$2")"; }

ef_write_build_env() {  # file state(BUILD|TEST) prefix build_prefix
  local file="$1" state="$2" H="$3" B="$4" kv k v f plat
  rm -f "$file"
  plat="$U_TARGET"; [ "$plat" = native ] && plat="$EF_BUILD_PLATFORM"
  [ -n "$U_NOARCH" ] && plat=noarch
  {
    echo "# build environment written by emforge-export for $U_IDENT"
    ef_kv PYTHONNOUSERSITE 1
    case "$plat" in *-*) ef_kv ARCH "${plat##*-}" ;; esac
    ef_kv CONDA_DEFAULT_ENV "$H"
    ef_kv PREFIX "$H"
    ef_kv BUILD_PREFIX "$B"
    ef_kv RECIPE_DIR "$EF_RECIPE_DIR"
    ef_kv SRC_DIR "$EF_W"
    ef_kv BUILD_DIR "$EF_BLD"
    ef_kv RATTLER_BUILD_PACKAGE_FILES "$EF_BLD/package_files.txt"
    ef_kv PIP_NO_BUILD_ISOLATION False
    ef_kv PIP_NO_DEPENDENCIES True
    ef_kv PIP_IGNORE_INSTALLED True
    ef_kv PIP_CACHE_DIR "$EF_BLD/pip_cache"
    ef_kv PIP_NO_INDEX True
    [ "$U_NOARCH" = python ] && ef_kv PYTHONDONTWRITEBYTECODE 1
    if [ "$U_KIND" = package ]; then
      ef_kv PKG_NAME "$U_NAME"; ef_kv PKG_VERSION "$U_VERSION"; ef_kv PKG_BUILDNUM "$U_BUILDNUM"
      ef_kv PKG_BUILD_STRING "$U_BUILDSTR"; ef_kv PKG_HASH "$U_HASH"
    fi
    if [ "$U_TARGET" = native ]; then ef_kv CONDA_BUILD_CROSS_COMPILATION 0; else ef_kv CONDA_BUILD_CROSS_COMPILATION 1; fi
    ef_kv SUBDIR "$plat"
    ef_kv build_platform "$EF_BUILD_PLATFORM"
    ef_kv target_platform "$plat"
    ef_kv host_platform "$plat"
    ef_kv CONDA_BUILD_STATE "$state"
    ef_kv PYTHON "$H/bin/python"
    if [ -n "$U_PY_VER" ]; then
      ef_kv PY3K 1; ef_kv PY_VER "$U_PY_VER"
      ef_kv STDLIB_DIR "$H/lib/python$U_PY_VER"; ef_kv SP_DIR "$H/lib/python$U_PY_VER/site-packages"
    fi
    ef_kv SOURCE_DATE_EPOCH "$EF_EPOCH"
    ef_kv CPU_COUNT "$EF_JOBS"
    case "$plat" in linux-*) ef_kv SHLIB_EXT .so ;; osx-*) ef_kv SHLIB_EXT .dylib ;; *) ef_kv SHLIB_EXT .not_implemented ;; esac
    case "$EF_BUILD_PLATFORM" in
      linux-64) ef_kv BUILD x86_64-conda_cos6-linux-gnu ;;
      linux-aarch64) ef_kv BUILD aarch64-conda_cos7-linux-gnu ;;
      linux-ppc64le) ef_kv BUILD powerpc64le-conda_cos7-linux-gnu ;;
    esac
    if [ "$EF_ISOLATION" = strict ]; then
      ef_kv LANG C.UTF-8; ef_kv LC_ALL C.UTF-8; ef_kv HOME "$EF_W"; ef_kv USER rattler
      ef_kv SHELL /bin/bash; ef_kv EDITOR /bin/false; ef_kv TERM xterm-256color
    fi
    for kv in ${U_VARIANT[@]+"${U_VARIANT[@]}"}; do ef_kv "${kv%%=*}" "${kv#*=}"; done
    for kv in ${U_SCRIPT_ENV[@]+"${U_SCRIPT_ENV[@]}"}; do
      k="${kv%%=*}"; v="${kv#*=}"
      echo "export $k=$(ef_q "$v")"
    done
    echo 'export CONDA_BUILD=1'
    # compatibility: recipes last built with CMake 3 that declare
    # cmake_minimum_required(< 3.5) still configure with the CMake 4 the
    # variant pins (a recipe may override this)
    echo 'export CMAKE_POLICY_VERSION_MINIMUM="${CMAKE_POLICY_VERSION_MINIMUM:-3.5}"'
    # activation: host prefix first, then build prefix (rattler-build order)
    local P
    for P in "$H" "$B"; do
      [ "$P" = "$H" ] || [ "$B" != "$H" ] || continue
      echo "export CONDA_PREFIX=$(ef_q "$P")"
      echo "export PATH=$(ef_q "$P/bin"):\"\$PATH\""
      ef_helper env-vars-d "$P"
      if [ -d "$P/etc/conda/activate.d" ]; then
        for f in $(cd "$P/etc/conda/activate.d" && ls | LC_ALL=C sort); do
          case "$f" in *.sh) echo ". $(ef_q "$P/etc/conda/activate.d/$f")" ;; esac
        done
      fi
    done
  } > "$file"
}

ef_write_script() {  # out-file
  local out="$1" body="$EF_BLD/script_body.sh"
  rm -f "$out" "$EF_W"/conda_build_script.*
  case "$U_SCRIPT" in
    file)
      tr -d '\r' < "$EF_RECIPE_DIR/$U_SCRIPT_FILE" > "$body" ;;
    inline)
      "$(ef_unit_fn "$EF_CUR")_script" > "$body.tmpl"
      ef_helper subst "$body.tmpl" "$body" ;;
    *) : > "$body" ;;
  esac
  {
    echo '#!/usr/bin/env bash'
    echo 'set -e'
    echo '## Start of bash preamble'
    echo 'if [ -z ${CONDA_BUILD+x} ]; then'
    echo "    source $(ef_q "$EF_W/build_env.sh")"
    echo 'fi'
    echo '## End of preamble'
    [ -n "$U_CWD" ] && echo "cd $(ef_q "$U_CWD")"
    case "$U_INTERP" in
      ""|bash|sh) cat "$body" ;;
      python) cp "$body" "$EF_W/conda_build_script.py"
              echo "\"\$BUILD_PREFIX/bin/python\" $(ef_q "$EF_W/conda_build_script.py")" ;;
      perl)   cp "$body" "$EF_W/conda_build_script.pl"; echo "perl $(ef_q "$EF_W/conda_build_script.pl")" ;;
      nodejs) cp "$body" "$EF_W/conda_build_script.js"; echo "node $(ef_q "$EF_W/conda_build_script.js")" ;;
      *) ef_die "unsupported script interpreter '$U_INTERP'" ;;
    esac
  } > "$out"
  chmod +x "$out"
}

ef_run_in_env() {  # log-file cwd script
  local log="$1" cwd="$2" script="$3" rc
  local envargs=()
  if [ "$EF_ISOLATION" = strict ]; then
    envargs=(env -i "PATH=$EF_SYS_PATH")
    local v
    for v in SSL_CERT_FILE SSL_CERT_DIR REQUESTS_CA_BUNDLE SSH_AUTH_SOCK DISPLAY http_proxy https_proxy \
             HTTP_PROXY HTTPS_PROXY no_proxy NO_PROXY TMPDIR NODE_EXTRA_CA_CERTS GIT_SSL_CAINFO \
             CURL_CA_BUNDLE PIP_CERT EF_PKG_CONFIG_SYSTEM; do
      if [ -n "${!v+x}" ]; then envargs+=("$v=${!v}"); fi
    done
  else
    envargs=(env "PATH=$EF_SYS_PATH")
  fi
  # run in the background and wait: 'wait' can be interrupted by a signal,
  # so Ctrl-C / kill stop the build at once (see ef_on_signal); pipefail
  # makes the pipeline's status the build's
  set +e
  (cd "$cwd" && "${envargs[@]}" bash "$script" < /dev/null) 2>&1 | tee -a "$log" &
  wait $!
  rc=$?
  set -e
  return $rc
}

# copy a directory's contents; copy-on-write where the filesystem can
ef_copy_tree() {  # src dst
  mkdir -p "$2"
  if [ -z "${EF_CP_REFLINK+x}" ]; then
    EF_CP_REFLINK=""; cp --reflink=auto --version >/dev/null 2>&1 && EF_CP_REFLINK="--reflink=auto"
  fi
  # shellcheck disable=SC2086
  cp -a $EF_CP_REFLINK "$1/." "$2/"
}

# Empty the build directory: it is renamed and deleted in the background
# (deleting a big source tree file by file can take minutes)
EF_TRASH_PID=""
ef_reset_bld() {
  if [ -e "$EF_BLD" ]; then
    local t="$EF_ROOT/tmp/trash-$$-$RANDOM"
    # one deletion at a time, so trash cannot pile up faster than it goes
    if [ -n "$EF_TRASH_PID" ]; then wait "$EF_TRASH_PID" 2>/dev/null || true; EF_TRASH_PID=""; fi
    if mv "$EF_BLD" "$t" 2>/dev/null; then
      ( chmod -R u+w "$t" 2>/dev/null; rm -rf "$t" ) >/dev/null 2>&1 &
      EF_TRASH_PID=$!
    else
      chmod -R u+w "$EF_BLD" 2>/dev/null || true; rm -rf "$EF_BLD"
    fi
  fi
  mkdir -p "$EF_BLD"
}

ef_build_unit() {  # n
  local n="$1" t0 pkgdir H B W x before after spec_json rc
  EF_CUR="$n"
  ef_load_unit "$n"
  pkgdir="$EF_PKGS/$U_IDENT"
  t0=$(date +%s)
  ef_info "==> [$EF_STEP/$EF_NSTEPS] building $U_IDENT"
  local x; for x in ${U_NOTES[@]+"${U_NOTES[@]}"}; do ef_log "note: $x"; done
  EF_W="$EF_BLD/work"; EF_H="$EF_BLD/host_env"; EF_B="$EF_BLD/build_env"
  [ "$U_MERGE_ENVS" = 1 ] && EF_B="$EF_H"
  H="$EF_H"; B="$EF_B"; W="$EF_W"
  EF_RECIPE_DIR="$EF_RECIPES/$U_RECIPE"
  EF_EPOCH="$(date +%s)"
  local log="$EF_LOGS/$U_IDENT.log"
  : > "$log"
  ef_reset_bld; mkdir -p "$W" "$H"
  local tspec
  # 1. staging cache
  if [ -n "$U_STAGING" ]; then
    local sd="$EF_PKGS/$U_STAGING"
    [ -f "$sd/.ef-done" ] || ef_die "staging cache $U_STAGING missing"
    ef_copy_tree "$sd/prefix" "$H"
    # --link-staging: hard-link the (often big) work directory instead of
    # copying it; a fingerprint taken now and after the script detects a
    # script that changed the cache's files in place
    if [ "$EF_LINK_STAGING" = 1 ] && cp -al "$sd/work/." "$W/" 2>/dev/null; then
      ef_helper tree-state "$sd/work" > "$EF_BLD/staging_state"
    else
      rm -rf "$W"; mkdir -p "$W"; ef_copy_tree "$sd/work" "$W"
    fi
    ef_log "restored staging cache $U_STAGING"
  fi
  # files of $PREFIX that belong to this package even though they exist
  # before its script runs: the staging cache's
  "$EF_PY" -I "$EF_HELPER" snapshot "$H" "$EF_BLD/staging_files.txt"
  # 2. sources
  EF_LAST_DEST="$W"
  "$(ef_unit_fn "$n")_sources" 2>&1 | tee -a "$log"
  [ "${PIPESTATUS[0]}" = 0 ] || ef_die "fetching sources of $U_IDENT failed"
  # 3. BUILD_PREFIX: python venv + build packages + tools
  if [ "$U_MERGE_ENVS" = 1 ]; then
    local tmpb="$EF_BLD/merged_tmp"
    ef_make_build_prefix "$tmpb" "$U_PY_SPEC" "$U_PY_PREF"
    cp -a "$tmpb/." "$H/"; rm -rf "$tmpb"
  else
    ef_make_build_prefix "$B" "$U_PY_SPEC" "$U_PY_PREF"
  fi
  ef_fill_build_prefix "$B" "$U_IDENT" U_BUILD_PKGS U_TOOLS U_PIP_BUILD
  # 4. host prefix
  for x in ${U_HOST_PKGS[@]+"${U_HOST_PKGS[@]}"}; do ef_install_pkg "$x" "$H" copy; done
  local hreqs=()
  for tspec in ${U_PIP_HOST[@]+"${U_PIP_HOST[@]}"}; do hreqs+=("$(ef_helper pip-spec "${tspec%%|*}" "${tspec#*|}")"); done
  ef_pypi_into "$H" "$B/bin/python" ${hreqs[@]+"${hreqs[@]}"}
  "$EF_PY" -I "$EF_HELPER" snapshot "$H" "$EF_BLD/snap_after.txt"
  # 5. run the build script
  ef_write_build_env "$W/build_env.sh" BUILD "$H" "$B"
  ef_write_script "$W/conda_build.sh"
  ef_log "running build script (log: $log)"
  if ! ef_run_in_env "$log" "$W" "$W/conda_build.sh"; then
    echo >&2
    ef_log "build directory kept for inspection: $EF_BLD"
    ef_log "re-run the script by hand:  cd $W && bash conda_build.sh"
    ef_die "build script of $U_IDENT failed (log: $log)"
  fi
  if [ -s "$EF_BLD/staging_state" ] && \
     [ "$(ef_helper tree-state "$EF_PKGS/$U_STAGING/work")" != "$(cat "$EF_BLD/staging_state")" ]; then
    ef_warn "the script of $U_IDENT changed files of staging cache $U_STAGING in place; it will be rebuilt before it is used again"
    rm -f "$EF_PKGS/$U_STAGING/.ef-done"
  fi
  # 6. collect
  rm -rf "$pkgdir"; mkdir -p "$pkgdir/info"
  spec_json="$EF_BLD/files_spec.json"
  ef_files_spec_json > "$spec_json"
  # everything in $PREFIX before the script ran (dependencies, a merged
  # build prefix) except the staging cache's files is not part of the package
  "$EF_PY" -I - "$EF_BLD/staging_files.txt" "$EF_BLD/snap_after.txt" "$EF_BLD/installed.txt" <<'PYEOF'
import sys
s = set(open(sys.argv[1]).read().split("\n")); a = open(sys.argv[2]).read().split("\n")
open(sys.argv[3], "w").write("\n".join(x for x in a if x and x not in s) + "\n")
PYEOF
  if [ "$U_KIND" = staging ]; then
    ef_helper collect "$H" "$EF_BLD/installed.txt" "$pkgdir/prefix" "$pkgdir/info" "$H" "$spec_json" >/dev/null
    mkdir -p "$pkgdir/work"; cp -a "$W/." "$pkgdir/work/"
  else
    ef_helper collect "$H" "$EF_BLD/installed.txt" "$pkgdir/files" "$pkgdir/info" "$H" "$spec_json" >/dev/null
    ef_write_index_json "$pkgdir/info/index.json"
    printf '%s\n' "$U_ABOUT_JSON" > "$pkgdir/info/about.json"
    printf '%s\n' "$U_RUN_EXPORTS_JSON" > "$pkgdir/info/run_exports.json"
    : > "$pkgdir/info/ef_pypi.txt"
    for tspec in ${U_RUN_PIP[@]+"${U_RUN_PIP[@]}"}; do
      ef_helper pip-spec "${tspec%%|*}" "${tspec#*|}" >> "$pkgdir/info/ef_pypi.txt"
    done
    mkdir -p "$pkgdir/info/recipe"
    cp -a "$EF_RECIPE_DIR/." "$pkgdir/info/recipe/" 2>/dev/null || true
    if [ ${#U_LICENSES[@]} -gt 0 ]; then
      local lic=() l
      for l in "${U_LICENSES[@]}"; do
        l="${l//@@EF:PREFIX@@/$H}"; l="${l//@@EF:BUILD_PREFIX@@/$B}"; l="${l//@@EF:SRC_DIR@@/$W}"
        l="${l//@@EF:RECIPE_DIR@@/$EF_RECIPE_DIR}"; l="${l//@@EF:BUILD_DIR@@/$EF_BLD}"; lic+=("$l")
      done
      ef_helper licenses "$pkgdir/info" "$W" "$EF_RECIPE_DIR" "${lic[@]}" >/dev/null
    fi
    # 7. package_contents tests (script tests run after all builds)
    ef_run_tests "$pkgdir" "$log"
  fi
  printf '%s' "$U_INPUT_HASH" > "$pkgdir/.ef-done"
  ef_ok "    done: $U_IDENT ($(( $(date +%s) - t0 ))s, $(wc -l < "$pkgdir/info/files" | tr -d ' ') files)"
}

# install build packages, native tools and pip packages into a BUILD_PREFIX
ef_fill_build_prefix() {  # dir ident pkgs-array-name tools-array-name pip-array-name
  local dir="$1" who="$2" x tspec
  local -a _pk _tl _pp
  eval "_pk=(\${$3[@]+\"\${$3[@]}\"})"; eval "_tl=(\${$4[@]+\"\${$4[@]}\"})"
  eval "_pp=(\${$5[@]+\"\${$5[@]}\"})"
  local EF_B="$dir"
  for x in ${_pk[@]+"${_pk[@]}"}; do ef_install_pkg "$x" "$dir" link; done
  EF_MISSING=(); EF_MISSING_PKGS=()
  local nm
  for tspec in ${_tl[@]+"${_tl[@]}"}; do
    nm=${#EF_MISSING[@]}
    if ! ef_tool "${tspec%%|*}" "${tspec#*|}"; then
      # a failed bootstrap (download, build) that was not recorded yet
      [ ${#EF_MISSING[@]} -gt "$nm" ] || EF_MISSING+=("${tspec%%|*} (could not be provided, see the errors above)")
    fi
  done
  if [ ${#EF_MISSING[@]} -gt 0 ]; then
    ef_report_missing
    ef_die "missing build tools for $who"
  fi
  for tspec in ${_pp[@]+"${_pp[@]}"}; do ef_pip_build "${tspec%%|*}" "${tspec#*|}"; done
  ef_pip_flush
  if [ -d "$dir/share/aclocal" ]; then
    local acl="$dir/share/aclocal" d
    for d in /usr/local/share/aclocal /usr/share/aclocal /opt/homebrew/share/aclocal; do
      [ -d "$d" ] && [ "$(ef_which_system aclocal 2>/dev/null)" != "" ] && \
        case "$(ef_realpath "$(command -v aclocal 2>/dev/null || echo /x)")" in "$EF_TOOLS"/*) acl="$acl:$d" ;; esac
    done
    ef_activation_script "activate-ef-aclocal.sh" "export ACLOCAL_PATH=$(ef_q "$acl")\${ACLOCAL_PATH:+:\$ACLOCAL_PATH}"
  fi
}

# pure-Python packages from PyPI that the packages in a (target) prefix
# need at run time (info/ef_pypi.txt), plus extra requirements
ef_pypi_into() {  # prefix python [req...]
  local P="$1" py="$2" f reqs=() pyver excl="" n
  shift 2
  for f in "$P"/conda-meta/*.json; do
    [ -f "$f" ] || continue
    n="$("$EF_PY" -c 'import json,sys;d=json.load(open(sys.argv[1]));print(d.get("ef_package_dir",""))' "$f")"
    if [ -n "$n" ] && [ -s "$n/info/ef_pypi.txt" ]; then
      while IFS= read -r x; do [ -n "$x" ] && reqs+=("$x"); done < "$n/info/ef_pypi.txt"
    fi
  done
  reqs+=("$@")
  [ ${#reqs[@]} -eq 0 ] && return 0
  pyver="$(cd "$P/lib" 2>/dev/null && ls -d python3.* 2>/dev/null | head -n 1 | sed 's/^python//')"
  [ -z "$pyver" ] && pyver="${U_PY_VER:-$EF_BUILD_PY_VER}"
  if [ -z "$py" ] || [ ! -x "$py" ]; then py="$(ef_pip_python)"; fi
  # names of every package of the plan: never replaced by a PyPI download
  excl="$(ef_plan_names | tr ' ' ',')"
  ef_log "PyPI (pure Python) into $(basename "$P"): ${reqs[*]}"
  ef_helper pypi-install "$py" "$P" "$pyver" "$EF_CACHE/pip" "$excl" "${reqs[@]}" \
    || ef_die "installing pure-Python packages from PyPI failed: ${reqs[*]}"
}

ef_plan_names() { local n; for n in "${EF_ORDER[@]}"; do ef_load_unit "$n"; printf '%s ' "$U_NAME"; done; }

# a python with pip, for PyPI installs outside of a build
ef_pip_python() {
  local d="$EF_TOOLS/pip-venv"
  if [ ! -x "$d/bin/python" ]; then
    ef_make_build_prefix "$d" "" "" >&2
  fi
  echo "$d/bin/python"
}

ef_files_spec_json() {
  "$EF_PY" -c 'import json,sys
a=sys.argv[1:]; i=a.index("--"); j=a.index("--",i+1)
print(json.dumps({"include":a[:i],"exclude":a[i+1:j],"always_include":a[j+1:]}))' \
    ${U_FILES_INCLUDE[@]+"${U_FILES_INCLUDE[@]}"} -- ${U_FILES_EXCLUDE[@]+"${U_FILES_EXCLUDE[@]}"} -- \
    ${U_ALWAYS_INCLUDE[@]+"${U_ALWAYS_INCLUDE[@]}"}
}

ef_write_index_json() {
  local plat="$U_TARGET"; [ "$plat" = native ] && plat="$EF_BUILD_PLATFORM"
  [ -n "$U_NOARCH" ] && plat=noarch
  "$EF_PY" -c 'import json,sys,time
a=sys.argv[1:]
name,ver,build,num,subdir,noarch,lic=a[:7]; rest=a[7:]
i=rest.index("--"); deps=rest[:i]; cons=rest[i+1:]
d={"name":name,"version":ver,"build":build,"build_number":int(num),"subdir":subdir,
   "depends":deps,"constrains":cons,"timestamp":int(time.time()*1000)}
if noarch: d["noarch"]=noarch
if lic: d["license"]=lic
print(json.dumps(d,indent=1))' "$U_NAME" "$U_VERSION" "$U_BUILDSTR" "$U_BUILDNUM" "$plat" "$U_NOARCH" "$U_LICENSE" \
    ${U_RUN_SPECS[@]+"${U_RUN_SPECS[@]}"} -- ${U_CONSTRAINS[@]+"${U_CONSTRAINS[@]}"} > "$1"
}

ef_run_tests() {  # pkgdir log
  local pkgdir="$1" log="$2" n i kind plat
  [ "$EF_SKIP_TESTS" = 1 ] && return 0
  plat="$U_TARGET"; [ "$plat" = native ] && plat="$EF_BUILD_PLATFORM"
  n="$(printf '%s' "$U_TESTS_JSON" | "$EF_PY" -c 'import json,sys;print(len(json.load(sys.stdin)))')"
  i=0
  while [ "$i" -lt "$n" ]; do
    kind="$(printf '%s' "$U_TESTS_JSON" | "$EF_PY" -c 'import json,sys;print(json.load(sys.stdin)['"$i"']["type"])')"
    case "$kind" in
      package_contents)
        printf '%s' "$U_TESTS_JSON" | "$EF_PY" -c 'import json,sys;print(json.dumps(json.load(sys.stdin)['"$i"']["spec"]))' > "$EF_BLD/test_$i.json"
        ef_helper test-contents "$pkgdir" "$EF_BLD/test_$i.json" "$plat" "$U_NOARCH" 2>&1 | tee -a "$log"
        if [ "${PIPESTATUS[0]}" != 0 ]; then
          [ "$EF_STRICT_TESTS" = 1 ] && ef_die "package_contents test of $U_IDENT failed"
          ef_warn "package_contents test of $U_IDENT failed (see above; --strict-tests makes this an error)"
        fi
        ;;
      *) ;;
    esac
    i=$((i + 1))
  done
}

ef_run_script_test() {  # index pkgdir log
  local i="$1" pkgdir="$2" log="$3" T="$EF_BLD/test_env" TB="$EF_BLD/test_build_env" TD="$EF_BLD/test_dir" x
  ef_info "    running script test $i of $U_IDENT"
  chmod -R u+w "$T" "$TB" "$TD" 2>/dev/null || true
  rm -rf "$T" "$TB" "$TD"; mkdir -p "$T" "$TD"
  EF_W="$EF_BLD/work"; EF_RECIPE_DIR="$EF_RECIPES/$U_RECIPE"; mkdir -p "$EF_W"
  # test BUILD_PREFIX: the test's build requirements
  ef_make_build_prefix "$TB" "$U_PY_SPEC" "$U_PY_PREF"
  ef_fill_build_prefix "$TB" "tests of $U_IDENT" U_TEST_BUILD_PKGS U_TEST_TOOLS U_TEST_PIP_BUILD
  # test PREFIX: the package, its run dependencies and the test's
  ef_helper install "$pkgdir" "$T" copy
  for x in ${U_TEST_PKGS[@]+"${U_TEST_PKGS[@]}"}; do ef_install_pkg "$x" "$T" copy; done
  local treqs=() tspec
  for tspec in ${U_TEST_PIP_RUN[@]+"${U_TEST_PIP_RUN[@]}"}; do treqs+=("$(ef_helper pip-spec "${tspec%%|*}" "${tspec#*|}")"); done
  if [ "$U_TARGET" = native ]; then
    [ ${#treqs[@]} -gt 0 ] && EF_PIP_QUEUE=("${treqs[@]}") && EF_B="$TB" ef_pip_flush
  else
    ef_pypi_into "$T" "$TB/bin/python" ${treqs[@]+"${treqs[@]}"}
  fi
  printf '%s' "$U_TESTS_JSON" > "$EF_BLD/tests.json"
  "$EF_PY" - "$i" "$EF_RECIPE_DIR" "$EF_W" "$TD" "$TD/test_body.sh" "$EF_BLD/tests.json" <<'PYEOF'
import json, os, shutil, sys, glob
t = json.load(open(sys.argv[6]))[int(sys.argv[1])]
recipe, work, td, body = sys.argv[2:6]
def cp(base, pats):
    for p in pats:
        for m in glob.glob(os.path.join(base, p.rstrip("/"))):
            rel = os.path.relpath(m, base); d = os.path.join(td, rel)
            os.makedirs(os.path.dirname(d), exist_ok=True)
            (shutil.copytree(m, d, symlinks=True, dirs_exist_ok=True) if os.path.isdir(m) else shutil.copy2(m, d))
cp(recipe, t["files"]["recipe"]); cp(work, t["files"]["source"])
s = t["script"]
if s["type"] == "file":
    text = open(os.path.join(recipe, s["path"])).read()
else:
    text = "\n".join(s.get("content") or [])
open(body, "w").write(text + "\n")
PYEOF
  ef_helper subst "$TD/test_body.sh" "$TD/test_body.sh"
  EF_W="$TD" ef_write_build_env "$TD/test_env.sh" TEST "$T" "$TB"
  {
    echo '#!/usr/bin/env bash'; echo 'set -e'
    echo "source $(ef_q "$TD/test_env.sh")"
    cat "$TD/test_body.sh"
  } > "$TD/run_test.sh"
  if ! ef_run_in_env "$log" "$TD" "$TD/run_test.sh"; then
    ef_warn "script test $i of $U_IDENT FAILED (log: $log, dir: $TD)"
    return 1
  fi
  ef_ok "    script test $i of $U_IDENT passed"
}

# run the script tests of unit n (after all builds)
ef_test_unit() {  # n
  local n="$1" i kind cnt rc=0
  ef_load_unit "$n"
  [ "$U_KIND" = package ] || return 0
  local pkgdir="$EF_PKGS/$U_IDENT" log="$EF_LOGS/$U_IDENT.test.log"
  [ -f "$pkgdir/.ef-done" ] || ef_die "$U_IDENT is not built"
  EF_EPOCH="$(date +%s)"
  : > "$log"
  cnt="$(printf '%s' "$U_TESTS_JSON" | "$EF_PY" -c 'import json,sys;print(len(json.load(sys.stdin)))')"
  i=0
  while [ "$i" -lt "$cnt" ]; do
    kind="$(printf '%s' "$U_TESTS_JSON" | "$EF_PY" -c 'import json,sys;print(json.load(sys.stdin)['"$i"']["type"])')"
    case "$kind" in
      script) ef_reset_bld
              ef_run_script_test "$i" "$pkgdir" "$log" || rc=1 ;;
      package_contents) ;;
      *) ef_log "test $i of $U_IDENT: type '$kind' is not supported by the standalone build; skipped" ;;
    esac
    i=$((i + 1))
  done
  return $rc
}

ef_report_missing() {
  local m pm
  ef_warn "the following build tools are missing and cannot be bootstrapped:"
  for m in "${EF_MISSING[@]}"; do printf '    - %s\n' "$m" >&2; done
  pm="$(ef_pkg_manager)"
  if [ ${#EF_MISSING_PKGS[@]} -gt 0 ]; then
    case "$pm" in
      apt) printf '  install with:  sudo apt-get install -y %s\n' "${EF_MISSING_PKGS[*]}" >&2 ;;
      dnf) printf '  install with:  sudo dnf install -y %s\n' "${EF_MISSING_PKGS[*]}" >&2 ;;
      brew) printf '  install with:  brew install %s\n' "${EF_MISSING_PKGS[*]}" >&2 ;;
      pacman) printf '  install with:  sudo pacman -S --needed %s\n' "${EF_MISSING_PKGS[*]}" >&2 ;;
    esac
  fi
}

ef_install_system_deps() {
  local pm sudo=""
  pm="$(ef_pkg_manager)"
  [ "$(id -u)" != 0 ] && command -v sudo >/dev/null 2>&1 && sudo=sudo
  [ ${#EF_MISSING_PKGS[@]} -eq 0 ] && return 0
  ef_info "installing system packages: ${EF_MISSING_PKGS[*]}"
  case "$pm" in
    apt) $sudo apt-get update && $sudo apt-get install -y "${EF_MISSING_PKGS[@]}" ;;
    dnf) $sudo dnf install -y "${EF_MISSING_PKGS[@]}" ;;
    brew) brew install "${EF_MISSING_PKGS[@]}" ;;
    pacman) $sudo pacman -S --needed --noconfirm "${EF_MISSING_PKGS[@]}" ;;
    *) ef_die "no supported package manager found" ;;
  esac
}

# check (without changing anything) that every tool of the plan is available
ef_preflight() {
  local n tspec seen=() k
  EF_MISSING=(); EF_MISSING_PKGS=(); EF_UNKNOWN_TOOLS=()
  for k in bash tar gzip; do command -v "$k" >/dev/null 2>&1 || EF_MISSING+=("$k"); done
  command -v curl >/dev/null 2>&1 || command -v wget >/dev/null 2>&1 || EF_MISSING+=("curl (or wget)")
  for n in "${EF_PLAN[@]}"; do
    ef_load_unit "$n"
    if [ "$EF_FORCE" != 1 ] && ! ef_in_list "$U_NAME" ${EF_REBUILD[@]+"${EF_REBUILD[@]}"} && ef_unit_done "$n"; then continue; fi
    if ef_unit_needs_git "$n"; then command -v git >/dev/null 2>&1 || EF_MISSING+=("git"); fi
    for tspec in ${U_TOOLS[@]+"${U_TOOLS[@]}"} "patch|"; do
      ef_in_list "$tspec" ${seen[@]+"${seen[@]}"} && continue
      seen+=("$tspec")
      EF_DRY=1 ef_tool "${tspec%%|*}" "${tspec#*|}" || true
    done
  done
  local u; for u in ${EF_UNKNOWN_TOOLS[@]+"${EF_UNKNOWN_TOOLS[@]}"}; do
    ef_warn "build requirement '$u' is not known to this script and not on PATH"
  done
  if [ ${#EF_MISSING[@]} -gt 0 ]; then
    ef_report_missing
    if [ "$EF_INSTALL_SYSTEM_DEPS" = 1 ]; then
      ef_install_system_deps
      EF_INSTALL_SYSTEM_DEPS=0; ef_preflight; return $?
    fi
    return 1
  fi
  return 0
}

ef_unit_needs_git() { declare -f "$(ef_unit_fn "$1")_sources" | grep -q 'ef_src_git'; }

ef_print_plan() {
  local n s
  echo "Build plan (${#EF_PLAN[@]} packages, root: $EF_ROOT):"
  for n in "${EF_PLAN[@]}"; do
    ef_load_unit "$n"
    if ef_unit_done "$n"; then s="up to date"; else s="to build"; fi
    [ "$U_TEST_ONLY" = 1 ] && s="$s (for tests)"
    printf '  %-55s %-8s %s\n' "$U_IDENT" "$( [ "$U_TARGET" = native ] && echo native || echo "$U_TARGET" )" "$s"
  done
}

ef_assemble() {
  local d="$EF_PREFIX" n x ids=()
  if [ -e "$d" ] && [ ! -f "$d/.ef-prefix" ] && [ -n "$(ls -A "$d" 2>/dev/null)" ]; then
    ef_die "$d exists and was not created by this script; choose another --prefix"
  fi
  rm -rf "$d"; mkdir -p "$d"; touch "$d/.ef-prefix"
  for x in "${EF_FINAL_PKGS[@]}"; do ef_helper install "$EF_PKGS/$x" "$d" copy; done
  ef_pypi_into "$d" ""
  ef_ok "installed ${#EF_FINAL_PKGS[@]} package(s) into $d"
}

ef_write_channel() {
  local ch="$EF_ROOT/channel" n
  mkdir -p "$ch"
  for n in "${EF_PLAN[@]}"; do
    ef_load_unit "$n"
    [ "$U_KIND" = package ] || continue
    ef_helper conda-pkg "$EF_PKGS/$U_IDENT" "$ch" >/dev/null
  done
  ef_helper repodata "$ch"
  ef_ok "conda channel written to $ch (use: -c file://$ch)"
}

ef_resolve_selection() {  # names... -> EF_PLAN (subset with deps), EF_TEST_UNITS
  local want=("$@") n keep w found extra=""
  EF_SELECTED=("$@")
  [ ${#want[@]} -eq 0 ] && want=("${EF_TARGETS[@]}")
  for w in "${want[@]}"; do
    [ -n "$(ef_unit_of "$w")" ] || ef_die "unknown package '$w' (known: $(ef_names))"
  done
  # packages whose script tests run
  EF_TEST_UNITS=()
  if [ "$EF_RUN_TESTS" = 1 ]; then
    for w in "${want[@]}"; do EF_TEST_UNITS+=("$(ef_unit_of "$w")"); done
  fi
  EF_PLAN=()
  for n in "${EF_ORDER[@]}"; do
    keep=0
    for w in "${want[@]}"; do
      if ef_in_list "$n" $(ef_deps_of "$w"); then keep=1; fi
    done
    if [ "$EF_RUN_TESTS" = 2 ]; then
      ef_load_unit "$n"; [ "$keep" = 1 ] && [ "$U_TEST_ONLY" = 0 ] && EF_TEST_UNITS+=("$n")
    fi
    if [ $keep = 1 ]; then EF_PLAN+=("$n"); fi
  done
  # what the tests need
  if [ ${#EF_TEST_UNITS[@]} -gt 0 ]; then
    for n in "${EF_TEST_UNITS[@]}"; do ef_load_unit "$n"; extra="$extra $(ef_testdeps_of "$U_NAME")"; done
    local plan2=()
    for n in "${EF_ORDER[@]}"; do
      if ef_in_list "$n" "${EF_PLAN[@]}" $extra; then plan2+=("$n"); fi
    done
    EF_PLAN=("${plan2[@]}")
  fi
  return 0
}

ef_unit_by_ident() { local n; for n in "${EF_ORDER[@]}"; do ef_load_unit "$n"; [ "$U_IDENT" = "$1" ] && { echo "$n"; return 0; }; done; return 1; }

ef_names() { local n; for n in "${EF_ORDER[@]}"; do ef_load_unit "$n"; printf '%s ' "$U_NAME"; done; }

ef_compute_final() {
  local w x names
  EF_FINAL_PKGS=()
  if [ ${#EF_SELECTED[@]} -gt 0 ]; then names=("${EF_SELECTED[@]}"); else names=("${EF_TARGETS[@]}"); fi
  for w in "${names[@]}"; do
    for x in $(ef_final_of "$w"); do
      ef_in_list "$x" ${EF_FINAL_PKGS[@]+"${EF_FINAL_PKGS[@]}"} || EF_FINAL_PKGS+=("$x")
    done
  done
}

# one run per root at a time (they share the package store and bld/)
ef_lock_root() {
  local l="$EF_ROOT/.lock" pid
  if ! mkdir "$l" 2>/dev/null; then
    pid="$(cat "$l/pid" 2>/dev/null || true)"
    if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then
      ef_die "another build (pid $pid) is using $EF_ROOT; wait for it or use another --root"
    fi
    rm -rf "$l"; mkdir "$l" || ef_die "cannot lock $EF_ROOT"
  fi
  echo $$ > "$l/pid"
  trap 'rm -rf "$EF_ROOT/.lock"' EXIT
  trap 'ef_on_signal 130' INT
  trap 'ef_on_signal 143' TERM
}

# stop every process this script started (configure, make, compilers, ...):
# freeze the tree top-down (so nothing forks while it is walked), then
# terminate and resume every frozen process
EF_TREE=()
ef_freeze_tree() {  # pid
  local c
  for c in $(ps -eo pid=,ppid= 2>/dev/null | awk -v p="$1" '$2 == p { print $1 }'); do
    [ "$c" = "$BASHPID" ] && continue
    kill -STOP "$c" 2>/dev/null || continue
    EF_TREE+=("$c")
    ef_freeze_tree "$c"
  done
}
ef_on_signal() {
  trap - INT TERM
  printf '\n' >&2
  ef_log "interrupted: stopping the build"
  EF_TREE=()
  ef_freeze_tree $$
  local c
  for c in ${EF_TREE[@]+"${EF_TREE[@]}"}; do kill -TERM "$c" 2>/dev/null || true; done
  for c in ${EF_TREE[@]+"${EF_TREE[@]}"}; do kill -CONT "$c" 2>/dev/null || true; done
  exit "$1"
}

ef_main() {
  EF_ROOT="${EF_ROOT:-$EF_START_DIR/ef-build}"
  EF_JOBS="$(ef_cpu_count)"; EF_TOOLS_MODE=auto; EF_OFFLINE=0; EF_EXTRA_CACHES=""
  EF_ISOLATION=strict; EF_FORCE=0; EF_REBUILD=(); EF_RUN_TESTS=0; EF_SKIP_TESTS=0; EF_STRICT_TESTS=0
  EF_ASSEMBLE=1; EF_CONDA_PKGS=0; EF_LIST=0; EF_CHECK=0; EF_ONLY=""; EF_INSTALL_SYSTEM_DEPS=0
  EF_KEEP_WORK=0; EF_LINK_STAGING=0
  local args=() extract=""
  while [ $# -gt 0 ]; do
    case "$1" in
      -C|--root) EF_ROOT="$2"; shift ;;
      -p|--prefix) EF_PREFIX="$2"; shift ;;
      -j|--jobs) EF_JOBS="$2"; shift ;;
      -l|--list) EF_LIST=1 ;;
      --only) EF_ONLY="$2"; shift ;;
      --rebuild) EF_REBUILD+=("$2"); shift ;;
      --force) EF_FORCE=1 ;;
      --tests) EF_RUN_TESTS=1 ;;
      --tests-all) EF_RUN_TESTS=2 ;;
      --skip-tests) EF_SKIP_TESTS=1 ;;
      --strict-tests) EF_STRICT_TESTS=1 ;;
      --no-assemble) EF_ASSEMBLE=0 ;;
      --conda-pkgs) EF_CONDA_PKGS=1 ;;
      --check) EF_CHECK=1 ;;
      --tools) EF_TOOLS_MODE="$2"; shift ;;
      --install-system-deps) EF_INSTALL_SYSTEM_DEPS=1 ;;
      --offline) EF_OFFLINE=1 ;;
      --cache) EF_CACHE="$2"; shift ;;
      --source-cache) EF_EXTRA_CACHES="${EF_EXTRA_CACHES:+$EF_EXTRA_CACHES:}$(cd "$2" && pwd)"; shift ;;
      --isolation) EF_ISOLATION="$2"; shift ;;
      --keep-work) EF_KEEP_WORK=1 ;;
      --link-staging) EF_LINK_STAGING=1 ;;
      --extract) extract="$2"; shift ;;
      -h|--help) ef_usage; exit 0 ;;
      -*) ef_die "unknown option $1 (see --help)" ;;
      *) args+=("$1") ;;
    esac
    shift
  done
  case "$EF_TOOLS_MODE" in auto|system|bootstrap) ;; *) ef_die "--tools must be auto, system or bootstrap" ;; esac
  case "$EF_ISOLATION" in strict|none) ;; *) ef_die "--isolation must be strict or none" ;; esac
  EF_PY="$(ef_find_python)" || ef_die "python3 (>= 3.8) is required to run this script"
  EF_BUILD_PLATFORM="$(ef_detect_platform)"
  if [ "$EF_BUILD_PLATFORM" != "$EF_EXPORT_BUILD_PLATFORM" ]; then
    ef_warn "this script was generated for build platform $EF_EXPORT_BUILD_PLATFORM, running on $EF_BUILD_PLATFORM"
  fi
  if [ -n "$extract" ]; then
    EF_ROOT="$(mkdir -p "$extract" && cd "$extract" && pwd)"
    EF_SCRIPT_ID=x; EF_HELPER="$EF_ROOT/ef-helper.py"; ef_write_helper > "$EF_HELPER"
    ef_extract_payload "$EF_ROOT/recipes"; rm -f "$EF_ROOT/recipes/.ef-complete"
    ef_ok "recipe files written to $EF_ROOT/recipes, runtime helper to $EF_HELPER"; exit 0
  fi
  ef_setup_root
  [ "$EF_LIST" = 1 ] || ef_lock_root
  EF_SELECTED=()
  if [ -n "$EF_ONLY" ]; then
    local n; EF_PLAN=()
    for n in "${EF_ORDER[@]}"; do ef_load_unit "$n"; [ "$U_NAME" = "$EF_ONLY" ] && EF_PLAN=("$n"); done
    [ ${#EF_PLAN[@]} -eq 1 ] || ef_die "unknown package '$EF_ONLY'"
    EF_FORCE=1; EF_TEST_UNITS=()
    [ "$EF_RUN_TESTS" != 0 ] && EF_TEST_UNITS=("${EF_PLAN[@]}")
  else
    ef_resolve_selection ${args[@]+"${args[@]}"}
  fi
  if [ "$EF_LIST" = 1 ]; then ef_print_plan; exit 0; fi
  ef_info "emforge-export standalone build: ${EF_TARGETS[*]}"
  ef_log "root: $EF_ROOT   jobs: $EF_JOBS   tools: $EF_TOOLS_MODE   platform: $EF_BUILD_PLATFORM"
  if ! ef_preflight; then
    ef_die "install the missing tools (or re-run with --install-system-deps)"
  fi
  if [ "$EF_CHECK" = 1 ]; then ef_ok "all required tools are available"; exit 0; fi
  EF_NSTEPS=${#EF_PLAN[@]}; EF_STEP=0
  local n
  for n in "${EF_PLAN[@]}"; do
    EF_STEP=$((EF_STEP + 1))
    ef_load_unit "$n"
    if [ "$EF_FORCE" != 1 ] && ! ef_in_list "$U_NAME" ${EF_REBUILD[@]+"${EF_REBUILD[@]}"} && ef_unit_done "$n"; then
      ef_log "[$EF_STEP/$EF_NSTEPS] $U_IDENT is up to date"
      continue
    fi
    ef_load_unit "$n"
    if [ -n "$U_STAGING" ] && [ ! -f "$EF_PKGS/$U_STAGING/.ef-done" ]; then
      local m; m="$(ef_unit_by_ident "$U_STAGING")"
      [ -n "$m" ] || ef_die "no unit builds staging cache $U_STAGING"
      ef_build_unit "$m"
    fi
    ef_build_unit "$n"
  done
  local failed=()
  if [ ${#EF_TEST_UNITS[@]} -gt 0 ]; then
    ef_info "==> script tests"
    for n in "${EF_TEST_UNITS[@]}"; do
      ef_test_unit "$n" || { ef_load_unit "$n"; failed+=("$U_IDENT"); }
    done
  fi
  if [ "$EF_KEEP_WORK" != 1 ] && [ ${#failed[@]} -eq 0 ]; then ef_reset_bld; rmdir "$EF_BLD" 2>/dev/null || true; fi
  wait 2>/dev/null || true   # background deletions
  if [ "$EF_ASSEMBLE" = 1 ] && [ -z "$EF_ONLY" ]; then ef_compute_final; ef_assemble; fi
  [ "$EF_CONDA_PKGS" = 1 ] && ef_write_channel
  if [ ${#EF_WARNINGS[@]} -gt 0 ]; then
    ef_warn "${#EF_WARNINGS[@]} warning(s) were reported above"
  fi
  if [ ${#failed[@]} -gt 0 ]; then
    ef_die "script tests failed for: ${failed[*]} (logs: $EF_LOGS/*.test.log)"
  fi
  if [ "$EF_ASSEMBLE" = 1 ] && [ -z "$EF_ONLY" ]; then
    ef_ok "all done. installed into: $EF_PREFIX   (packages: $EF_PKGS)"
  else
    ef_ok "all done. packages: $EF_PKGS"
  fi
}
