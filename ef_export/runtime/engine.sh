ef_which_system() { PATH="$EF_SYS_PATH" command -v "$1" 2>/dev/null; }
ef_realpath() { ef_helper realpath "$1"; }
ef_in_list() { local x="$1"; shift; local y; for y in "$@"; do [ "$x" = "$y" ] && return 0; done; return 1; }
ef_hash_str() { printf '%s' "$1" | "$EF_PY" -c 'import hashlib,sys;print(hashlib.sha256(sys.stdin.buffer.read()).hexdigest()[:16])'; }

ef_tool_version() {  # exe version-args
  local exe="$1" args="$2" out
  [ -z "$args" ] && return 1
  # shellcheck disable=SC2086
  out="$("$exe" $args 2>&1 </dev/null | head -n 5)" || true
  printf '%s' "$out" | ef_helper first-version
}

ef_spec_ok() {  # version spec
  [ -z "$2" ] && return 0
  [ -z "$1" ] && return 1
  ef_helper spec-match "$1" "$2"
}

# mirror data paths of a system tool (e.g. share/libtool) into BUILD_PREFIX
ef_mirror_data() {  # exe-path globs...
  local exe="$1"; shift
  local real pfx g p rel
  real="$(ef_realpath "$exe")"
  pfx="$(dirname "$(dirname "$real")")"
  for g in "$@"; do
    for p in "$pfx"/$g; do
      [ -e "$p" ] || continue
      rel="${p#$pfx/}"
      [ -e "$EF_B/$rel" ] && continue
      mkdir -p "$(dirname "$EF_B/$rel")"
      ln -s "$p" "$EF_B/$rel"
    done
  done
}

# symlink-farm a tool prefix into BUILD_PREFIX (bin, share, lib, include)
ef_link_prefix() {  # tool-prefix
  local src="$1" f rel
  (cd "$src" && find . \( -type f -o -type l \) ! -name '.ef-done' -print) | while IFS= read -r f; do
    rel="${f#./}"
    case "$rel" in conda-meta/*|*.la) continue ;; esac
    [ -e "$EF_B/$rel" ] || [ -L "$EF_B/$rel" ] && continue
    mkdir -p "$(dirname "$EF_B/$rel")"
    ln -s "$src/$rel" "$EF_B/$rel"
  done
}

ef_activation_script() {  # name content  -> BUILD_PREFIX/etc/conda/activate.d/<name>
  mkdir -p "$EF_B/etc/conda/activate.d"
  printf '%s\n' "$2" > "$EF_B/etc/conda/activate.d/$1"
}

